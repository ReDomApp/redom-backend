import {
  pgTable,
  uuid,
  varchar,
  text,
  integer,
  boolean,
  timestamp,
  jsonb,
} from "drizzle-orm/pg-core";

import { conversations } from "./conversations";
import { userProfiles } from "./userProfiles";

export const messages = pgTable("messages", {
  id: uuid("id").defaultRandom().primaryKey(),
  conversationId: uuid("conversation_id").notNull().references(() => conversations.id),
  senderId: uuid("sender_id").notNull().references(() => userProfiles.id),
  parentMessageId: uuid("parent_message_id"),
  forwardedFromMessageId: uuid("forwarded_from_message_id"),
  messageType: varchar("message_type", { length: 40 }).default("text").notNull(),
  message: text("message"),
  caption: text("caption"),
  mentions: text("mentions"),
  hashtags: text("hashtags"),
  hyperlink: text("hyperlink"),
  richLinkPreview: boolean("rich_link_preview").default(false).notNull(),
  markdown: boolean("markdown").default(false).notNull(),
  codeBlock: boolean("code_block").default(false).notNull(),
  translated: boolean("translated").default(false).notNull(),
  /** Per-recipient encrypted envelopes. Plaintext is never required for encrypted chats. */
  encryptedPayload: jsonb("encrypted_payload"),
  encryptionVersion: integer("encryption_version"),
  encryptedAt: timestamp("encrypted_at", { withTimezone: true }),
  likeCount: integer("like_count").default(0).notNull(),
  loveCount: integer("love_count").default(0).notNull(),
  hahaCount: integer("haha_count").default(0).notNull(),
  wowCount: integer("wow_count").default(0).notNull(),
  sadCount: integer("sad_count").default(0).notNull(),
  angryCount: integer("angry_count").default(0).notNull(),
  reactionCount: integer("reaction_count").default(0).notNull(),
  isForwarded: boolean("is_forwarded").default(false).notNull(),
  edited: boolean("edited").default(false).notNull(),
  editedLabel: boolean("edited_label").default(false).notNull(),
  editedAt: timestamp("edited_at", { withTimezone: true }),
  pinned: boolean("pinned").default(false).notNull(),
  sent: boolean("sent").default(true).notNull(),
  delivered: boolean("delivered").default(false).notNull(),
  read: boolean("read").default(false).notNull(),
  readAt: timestamp("read_at", { withTimezone: true }),
  deletedForMe: boolean("deleted_for_me").default(false).notNull(),
  deletedForEveryone: boolean("deleted_for_everyone").default(false).notNull(),
  deletedPlaceholder: boolean("deleted_placeholder").default(false).notNull(),
  deletedAt: timestamp("deleted_at", { withTimezone: true }),
  aiReviewed: boolean("ai_reviewed").default(false).notNull(),
  moderationStatus: varchar("moderation_status", { length: 30 }).default("approved").notNull(),
  spamDetected: boolean("spam_detected").default(false).notNull(),
  scamDetected: boolean("scam_detected").default(false).notNull(),
  adultContentDetected: boolean("adult_content_detected").default(false).notNull(),
  violenceDetected: boolean("violence_detected").default(false).notNull(),
  hateSpeechDetected: boolean("hate_speech_detected").default(false).notNull(),
  malwareDetected: boolean("malware_detected").default(false).notNull(),
  reportCount: integer("report_count").default(0).notNull(),
  failedDelivery: boolean("failed_delivery").default(false).notNull(),
  restrictedMessage: boolean("restricted_message").default(false).notNull(),
  callType: varchar("call_type", { length: 30 }),
  callDurationSeconds: integer("call_duration_seconds"),
  systemAction: varchar("system_action", { length: 60 }),
  createdAt: timestamp("created_at", { withTimezone: true }).defaultNow().notNull(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).defaultNow().notNull(),
});
